                        'description' => 'Granular execution results for each verification check.',
                    ],
                    'failure_evidence' => [
                        'type' => 'object',
                        'properties' => [
                            'stdout' => ['type' => 'string'],
                            'stderr' => ['type' => 'string'],
                            'failed_tests' => [
                                'type' => 'array',
