    {
        return [
            'name' => 'record_review_verdict',
            'description' => 'Record adversarial review verdict, mitigation status, regression checks, and failure feedback.',
            'input_schema' => [
                'type' => 'object',
                'properties' => [
                    'approved' => [
                        'type' => 'boolean',
                        'description' => 'True if the candidate patch mitigates the vulnerability, introduces zero regressions, builds cleanly, and passes security scrutiny.',
                    ],
                    'verdict_summary' => [
                        'type' => 'string',
                        'description' => 'Concise summary of the audit verdict and findings.',
                    ],
                    'vulnerability_mitigated' => [
                        'type' => 'boolean',
                        'description' => 'True if the original vulnerability reproduction fails / exploit is successfully mitigated.',
                    ],
                    'regressions_detected' => [
                        'type' => 'boolean',
                        'description' => 'True if existing test suites or functionality broke due to the candidate patch.',
                    ],
                    'build_passed' => [
                        'type' => 'boolean',
                        'description' => 'True if build, compilation, and typecheck steps succeeded.',
